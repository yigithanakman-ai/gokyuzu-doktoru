  // Verilen burç ve dereceye en yakın sabit yıldızları bul (1.5° Orb içinde)
  static List<FixedStar> findConjunctions(String sign, double degree, {double orb = 1.5}) {
    final matches = <FixedStar>[];
    for (final star in allStars) {
      if (star.sign == sign) {
        final diff = (star.degree + (star.minute / 60.0) - degree).abs();
        if (diff <= orb) {
          matches.add(star);
        }
      }
    }
    return matches;
  }
