class FixedStar {
  final String name;
  final String sign;
  final double degree;
  final double minute;
  final String nature; // 'Şanslı', 'Talihsiz', 'Nötr', 'Çok Şanslı', 'Çok Talihsiz'
  final String planets; // 'Jüpiter/Mars', 'Satürn', vb.
  final String description;
  final Color color;

  const FixedStar({
    required this.name,
    required this.sign,
    required this.degree,
    required this.minute,
    required this.nature,
    required this.planets,
    required this.description,
    required this.color,
  });

  double get absoluteDegree {
    const signs = [
      'Koç', 'Boğa', 'İkizler', 'Yengeç', 'Aslan', 'Başak',
      'Terazi', 'Akrep', 'Yay', 'Oğlak', 'Kova', 'Balık'
    ];
    final idx = signs.indexOf(sign);
    if (idx == -1) return 0.0;
    return (idx * 30.0) + degree + (minute / 60.0);
  }

  String get degreeStr => '${degree.toInt()}°${minute.toInt().toString().padLeft(2, '0')}\' $sign';
  String get meaning => description;
  String get rulingPlanets => planets;
}

